# Define a termination condition that stops the task if the critic approves.
# text_termination = TextMentionTermination("APPROVE")
source_matchtermination = SourceMatchTermination(["critic"])

# Create a team with the primary and critic agents.
# team = RoundRobinGroupChat([primary_agent, critic_agent], termination_condition=text_termination)
team = RoundRobinGroupChat([primary_agent, critic_agent], termination_condition=source_matchtermination)

# Use `asyncio.run(...)` when running in a script.
async def main():
    stream = team.run_stream(task="编写3条用户登录的测试用例")
    async for item in stream:
        if isinstance(item, ModelClientStreamingChunkEvent): # 输出流,根据 source属性判断是哪个 agent
            print(item.content, end="", flush=True)
        if isinstance(item, TextMessage) and item.source == "primary":  # 表示primary智能体最终的完整输出
            print(item.content)
            break
        if isinstance(item, TextMessage) and item.source == "critic":  # 表示critic智能体最终的完整输出
            print(item.content)
            break
        if isinstance(item, TaskResult): # 包含所有智能体的输出,包括用户的输入
            print(item.messages) # 列表存储,每个元素是一个消息对象TextMessage,代表每个智能体的输出
        print(item)
